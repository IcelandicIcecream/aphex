#!/usr/bin/env node
// Writes src/upgrade/known-files.ts: for each file core now serves, the git blob id of
// every version `templates/base`, `templates/website` and `apps/studio` ever shipped,
// and a hash of every line those versions had. The upgrade deletes a file only when its
// blob id is listed, so a file someone edited is kept, and uses the line hashes to show
// which lines of an edited file are the person's own.
//
// Run from anywhere inside the monorepo: `node packages/create-aphex/scripts/known-files.mjs`.
// Rerun it whenever one of these files changes in the template, or before a release.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CORE_SERVED_PATHS } from '../dist/upgrade/units.js';
import { lineHash, meaningfulLines } from '../dist/upgrade/lines.js';

const git = (...args) =>
	execFileSync('git', args, { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
const root = git('rev-parse', '--show-toplevel').trim();
const prefixes = ['templates/base', 'templates/website', 'apps/studio'];

/** @type {Map<string, Set<string>>} */
const known = new Map();
/** @type {Map<string, string>} blob id -> path */
const blobsOf = new Map();
for (const prefix of prefixes) {
	const paths = CORE_SERVED_PATHS.map((path) => `${prefix}/${path}`);
	const commits = git('-C', root, 'rev-list', '--all', '--', ...paths)
		.split('\n')
		.filter(Boolean);
	for (const commit of commits) {
		const tree = git('-C', root, 'ls-tree', '-r', commit, '--', ...paths);
		for (const line of tree.split('\n')) {
			// <mode> blob <id>\t<path>
			const match = line.match(/^\d+ blob ([0-9a-f]{40})\t(.+)$/);
			if (!match) continue;
			const path = match[2].slice(prefix.length + 1);
			if (!known.has(path)) known.set(path, new Set());
			known.get(path).add(match[1]);
			blobsOf.set(match[1], path);
		}
	}
}

/** @type {Map<string, Set<string>>} */
const lines = new Map();
for (const [blob, path] of blobsOf) {
	if (!lines.has(path)) lines.set(path, new Set());
	for (const line of meaningfulLines(git('-C', root, 'cat-file', '-p', blob))) {
		lines.get(path).add(lineHash(line));
	}
}

const entries = [...known.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = entries
	.map(
		([path, ids]) =>
			`\t'${path}': [\n${[...ids]
				.sort()
				.map((id) => `\t\t'${id}'`)
				.join(',\n')}\n\t]`
	)
	.join(',\n');
const out = join(dirname(fileURLToPath(import.meta.url)), '../src/upgrade/known-files.ts');
writeFileSync(
	out,
	`// Generated by scripts/known-files.mjs. Don't edit by hand.\n` +
		`// Git blob ids of every version of each file that Aphex shipped and core now serves.\n` +
		`export const KNOWN_FILES: Record<string, readonly string[]> = {\n${body}\n};\n\n` +
		`// Space-separated line hashes (see lines.ts) per path, across all those versions.\n` +
		`export const KNOWN_LINES: Record<string, string> = {\n${entries
			.map(([path]) => `\t'${path}': '${[...lines.get(path)].sort().join(' ')}'`)
			.join(',\n')}\n};\n`
);
// Formatted like the rest of the repo, so a regenerate is a clean diff.
execFileSync('npx', ['prettier', '--write', out], { stdio: 'ignore' });
console.log(
	`${entries.length} paths, ${entries.reduce((n, [, ids]) => n + ids.size, 0)} versions -> ${out}`
);
