/**
 * Regenerates `src/lib/data` from a copy of `@phosphor-icons/core`:
 *
 *   npm pack @phosphor-icons/core@2.1.1 && tar xzf phosphor-icons-core-2.1.1.tgz
 *   node scripts/generate.mjs ./package
 *
 * One module per weight maps an icon's name to its path (`d`); duotone's maps to
 * `[path, shade]`, the shade being the 20% layer behind it. The catalog holds each
 * name with its search words. Kept as JSON.parse strings, which load faster than
 * object literals of this size.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const source = process.argv[2];
if (!source) {
	console.error('Usage: node scripts/generate.mjs <path to @phosphor-icons/core>');
	process.exit(1);
}
const root = resolve(source);
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const { icons } = await import(pathToFileURL(join(root, 'dist/index.mjs')).href);
const out = new URL('../src/lib/data/', import.meta.url);
const header = `// Generated by scripts/generate.mjs from @phosphor-icons/core ${version} (MIT). Don't edit.\n`;
const write = (name, value, type) => {
	writeFileSync(new URL(`${name}.js`, out), `${header}export default JSON.parse(${JSON.stringify(JSON.stringify(value))});\n`);
	writeFileSync(new URL(`${name}.d.ts`, out), `${header}declare const data: ${type};\nexport default data;\n`);
};

const WEIGHTS = ['regular', 'bold', 'fill', 'duotone', 'light', 'thin'];
for (const weight of WEIGHTS) {
	const dir = join(root, 'assets', weight);
	const data = {};
	for (const file of readdirSync(dir).sort()) {
		const name = file.replace(/\.svg$/, '').replace(new RegExp(`-${weight}$`), '');
		const svg = readFileSync(join(dir, file), 'utf8');
		const paths = [...svg.matchAll(/<path d="([^"]+)"( opacity="[^"]+")?\/>/g)];
		const main = paths.filter((p) => !p[2]).map((p) => p[1]).join(' ');
		const shade = paths.filter((p) => p[2]).map((p) => p[1]).join(' ');
		data[name] = weight === 'duotone' ? [main, shade] : main;
	}
	write(weight, data, weight === 'duotone' ? 'Record<string, [string, string]>' : 'Record<string, string>');
}

// Search words: the name's own words first, then tags and categories, without
// Phosphor's release markers (`*new*`).
const catalog = icons
	.map((icon) => [
		icon.name,
		[...new Set([...icon.tags, ...icon.categories].filter((word) => !word.startsWith('*')))].join(' ')
	])
	.sort((a, b) => a[0].localeCompare(b[0]));
write('catalog', catalog, '[name: string, words: string][]');
console.log(`Wrote ${catalog.length} icons in ${WEIGHTS.length} weights from @phosphor-icons/core ${version}.`);
